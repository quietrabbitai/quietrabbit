    #[derive(Deserialize)]
    struct CasePoint {
        text: String,
        keys: Vec<Vec<String>>,
    }

    #[derive(Deserialize)]
    struct Case {
        id: String,
        text: String,
        allowed: String,
        points: Vec<CasePoint>,
        expected: CheckReport,
    }

    #[derive(Deserialize)]
    struct Cases {
        cases: Vec<Case>,
    }

    fn run_case(c: &Case) -> CheckReport {
        let alts: Vec<Vec<Vec<&str>>> = c
            .points
            .iter()
            .map(|p| {
                p.keys
                    .iter()
                    .map(|g| g.iter().map(String::as_str).collect())
                    .collect()
            })
            .collect();
        let groups: Vec<Vec<&[&str]>> = alts
            .iter()
            .map(|p| p.iter().map(Vec::as_slice).collect())
            .collect();
        let points: Vec<Point> = c
            .points
            .iter()
            .zip(&groups)
            .map(|(p, g)| Point {
                text: &p.text,
                keys: g.as_slice(),
            })
            .collect();
        check(
            &c.text,
            &CheckInput {
                allowed_text: &c.allowed,
                points: &points,
            },
        )
    }

