// src-tauri/src/conductor/draft_check.rs
//
// items.id=899 stage 1 (decisions.id=942 addendum 3 d, decisions.id=950): the
// deterministic check of a draft for unsupported additions, as ONE shipped module.
// Its measures were written for the calibration example (examples/focus_calibration.rs,
// items.id=893 and 894 part 0) and are moved here UNCHANGED, so the example, the
// local calibration harness and the product use one copy. The characterization test
// (tests/fixtures/draft_check_cases.json) pins the pre-move output, quirks included.
//
// WHAT IT FINDS, per draft, with no model call and no I/O:
//   * bracketed placeholders ([Your Name], {date}, <Name>);
//   * opening chatter (remarks about the draft before it) and closing chatter;
//   * unsupported specifics: numbers, dates, spelled numbers and capitalised names
//     or places that are not in the allowed text (the brief, the sender details and
//     the context the draft was given);
//   * coverage of a brief's points, by keyword groups.
// The first three are the "unsupported additions" of decisions.id=942 addendum 3 d.
// Coverage is a measure, never a finding: a draft that leaves a point out is not
// regenerated by decide(). Keyword groups are authored per point, so a production
// caller with a free-text brief passes no points and gets findings only; the
// calibration corpus supplies them.
//
// STRICTNESS comes from the document type's latitude, through the existing
// CheckPolicy::for_latitude (model_block::document_type), and decide() is the one
// place that applies it:
//   strict  RegenerateOnceThenMark  a finding on attempt 0 is Regenerate, a finding
//                                   on a later attempt is Mark
//   framed  MarkOnly                a finding is Mark, never Regenerate
//   free    Off                     Skipped: no finding is recorded or shown
// Nothing in the executor calls this. Running the check after a draft step and the
// guarded second draft row are composition rows (items.id=903, 907, 908); latitude
// reaches them from run_settings::resolve_settings (Settings.latitude).
//
// KNOWN GAPS (printed on the calibration pages as well): soft embellishment with no
// number or capitalised name ("seasoned professional"), invented causes or
// consequences, lower-case invented groups, a reversed fact that keeps the right
// keywords, and a correct paraphrase that does not. So every draft is still
// presented as needing review. Known quirks pinned by the fixture: a citation such
// as [1] is read as an unsupported number, [2a] as a placeholder, and a short line
// of capitalised words is read as a name.
//
// No model or provider id appears here (a source scan in the tests pins that), and
// the module reads no file, database or network.

use std::collections::HashSet;

use serde::{Deserialize, Serialize};

use crate::conductor::model_block::document_type::{CheckPolicy, Latitude};

/// One point of a brief with the keyword groups that show a draft covers it:
/// every group must match, and a group matches when any of its alternatives is
/// found (lower case, at the start of a word) in the draft.
#[derive(Debug, Clone, Copy)]
pub struct Point<'a> {
    /// Shown on the calibration pages.
    pub text: &'a str,
    pub keys: &'a [&'a [&'a str]],
}

/// What a draft is checked against.
#[derive(Debug, Clone, Copy)]
pub struct CheckInput<'a> {
    /// The text a draft may draw its specifics from: the brief, the sender details
    /// and the context it was given.
    pub allowed_text: &'a str,
    /// Points for the coverage measure. Empty means coverage is not measured
    /// (points_total is 0).
    pub points: &'a [Point<'a>],
}

/// The measures of one draft. Findings are the first four fields after coverage.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct CheckReport {
    pub points_total: usize,
    pub points_covered: usize,
    pub missing_points: Vec<String>,
    /// Numbers, dates, spelled numbers and capitalised names or places that are
    /// not in the brief or persona context. A list for a reader to check.
    pub unsupported: Vec<String>,
    pub placeholders: Vec<String>,
    pub opening_chatter: Option<String>,
    pub closing_chatter: Option<String>,
}

/// Lower-cases and folds typographic quotes, dashes and no-break spaces, so the
/// keyword tests are not defeated by them.
fn norm(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '\u{2018}' | '\u{2019}' => '\'',
            '\u{2010}'..='\u{2015}' => '-',
            '\u{00a0}' => ' ',
            c => c,
        })
        .collect::<String>()
        .to_lowercase()
}

/// `term` (already lower case) occurs in `hay` at the start of a word.
fn has_term(hay: &str, term: &str) -> bool {
    hay.match_indices(term).any(|(i, _)| {
        hay[..i]
            .chars()
            .next_back()
            .is_none_or(|c| !c.is_alphanumeric())
    })
}

fn point_covered(hay: &str, keys: &[&[&str]]) -> bool {
    keys.iter()
        .all(|alts| alts.iter().any(|a| has_term(hay, a)))
}

/// Bracketed placeholders such as [Your Name], {date} or <Name>. Returns the spans
/// and the text with each span replaced by a space. A bracket pair with no letters
/// inside (a citation like [1]) or that starts with white space is not a span.
fn split_placeholders(text: &str) -> (Vec<String>, String) {
    let mut spans: Vec<String> = Vec::new();
    let mut rest = String::with_capacity(text.len());
    for (li, line) in text.lines().enumerate() {
        if li > 0 {
            rest.push('\n');
        }
        let chars: Vec<char> = line.chars().collect();
        let mut i = 0;
        while i < chars.len() {
            let close = match chars[i] {
                '[' => ']',
                '{' => '}',
                '<' => '>',
                c => {
                    rest.push(c);
                    i += 1;
                    continue;
                }
            };
            let end = chars[i + 1..].iter().take(80).position(|&c| c == close);
            if let Some(e) = end {
                let inner: String = chars[i + 1..i + 1 + e].iter().collect();
                if inner.chars().any(char::is_alphabetic)
                    && !inner.starts_with(char::is_whitespace)
                    && !inner.starts_with('/')
                {
                    spans.push(chars[i..i + e + 2].iter().collect());
                    rest.push(' ');
                    i += e + 2;
                    continue;
                }
            }
            rest.push(chars[i]);
            i += 1;
        }
    }
    (spans, rest)
}

fn starts_with_word(s: &str, w: &str) -> bool {
    s.starts_with(w)
        && s[w.len()..]
            .chars()
            .next()
            .is_none_or(|c| !c.is_alphanumeric())
}

/// First non-empty line is remarks about the draft rather than the draft.
fn opening_chatter(text: &str) -> Option<String> {
    const STARTS: &[&str] = &[
        "here is",
        "here's",
        "here are",
        "here you",
        "sure",
        "certainly",
        "of course",
        "absolutely",
        "okay",
        "ok",
        "below is",
        "i've written",
        "i have written",
        "i've drafted",
        "i have drafted",
        "i've put together",
        "happy to",
        "great",
    ];
    const WORDS: &[&str] = &[
        "draft", "letter", "email", "note", "essay", "section", "version",
    ];
    let first = text.lines().map(str::trim).find(|l| !l.is_empty())?;
    let low = norm(first);
    let low = low.trim_start_matches(|c: char| "*#>-_ ".contains(c));
    let starts = STARTS.iter().any(|s| starts_with_word(low, s));
    let colon = low.ends_with(':')
        && !low.starts_with("dear")
        && WORDS.iter().any(|w| low.contains(w))
        && low.split_whitespace().count() <= 14;
    (starts || colon).then(|| first.to_owned())
}

/// The last paragraph talks about the draft itself (an offer to revise, a note).
fn closing_chatter(text: &str) -> Option<String> {
    const PHRASES: &[&str] = &[
        "this draft",
        "this letter is",
        "this email is",
        "this note is",
        "i hope this helps",
        "hope this helps",
        "let me know if you'd like me",
        "let me know if you want me",
        "let me know if you would like me",
        "feel free to adjust",
        "feel free to modify",
        "feel free to customize",
        "feel free to customise",
        "you can adjust",
        "you may want to",
        "note:",
        "(note",
        "adjust as needed",
        "if you'd like me to",
        "if you would like me to",
        "would you like me to",
        "i can adjust",
        "i can revise",
    ];
    let last = text
        .split("\n\n")
        .map(str::trim)
        .filter(|p| !p.is_empty())
        .last()?;
    let low = norm(last);
    PHRASES
        .iter()
        .any(|p| low.contains(p))
        .then(|| last.lines().next().unwrap_or(last).to_owned())
}

